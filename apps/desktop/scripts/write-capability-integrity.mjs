import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const desktopRoot = path.resolve(here, '..');
const repositoryRoot = path.resolve(desktopRoot, '..', '..');
const source = path.join(repositoryRoot, 'packages', 'capabilities', 'src', 'windows-capability-bridge.ps1');
const outputDirectory = path.join(desktopRoot, 'build');
const manifestOutput = path.join(outputDirectory, 'windows-capability-bridge.sha256');
const generatedOutput = path.join(repositoryRoot, 'packages', 'capabilities', 'src', 'windows-capability-integrity.generated.ts');
const bytes = await readFile(source);
const sha256 = createHash('sha256').update(bytes).digest('hex');
await mkdir(outputDirectory, { recursive: true });
await writeFile(manifestOutput, sha256 + '  windows-capability-bridge.ps1\n', 'utf8');
await writeFile(generatedOutput, `// Generated by apps/desktop/scripts/write-capability-integrity.mjs.\nexport const WINDOWS_CAPABILITY_BRIDGE_SHA256 = '${sha256}' as const;\n`, 'utf8');
process.stdout.write('windows-capability-bridge sha256 ' + sha256 + '\n');
